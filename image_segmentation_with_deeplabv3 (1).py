# 1. Mini Synthetic Dataset Generator (10 Images)
os.makedirs("mini_dataset/images", exist_ok=True)
os.makedirs("mini_dataset/masks", exist_ok=True)

np.random.seed(42)
for i in range(10):
    img = np.zeros((128, 128, 3), dtype=np.uint8)
    mask = np.zeros((128, 128), dtype=np.uint8)

    # Generate random circle target
    cx, cy = np.random.randint(30, 98, size=2)
    r = np.random.randint(15, 30)

    cv2.circle(img, (cx, cy), r, (255, 255, 255), -1)
    cv2.circle(mask, (cx, cy), r, 255, -1)

    # Add random background noise
    noise = np.random.randint(0, 50, (128, 128, 3), dtype=np.uint8)
    img = cv2.add(img, noise)

    cv2.imwrite(f"mini_dataset/images/img_{i}.png", img)
    cv2.imwrite(f"mini_dataset/masks/mask_{i}.png", mask)

print("Mini dataset generated successfully!")

# 2. PyTorch Dataset Loader
class MiniSegmentationDataset(Dataset):
    def __init__(self, img_dir, mask_dir):
        self.img_dir = img_dir
        self.mask_dir = mask_dir
        self.images = sorted(os.listdir(img_dir))

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        img_path = os.path.join(self.img_dir, self.images[idx])
        mask_path = os.path.join(self.mask_dir, self.images[idx].replace("img", "mask"))

        image = cv2.imread(img_path)
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB) / 255.0
        mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE) / 255.0

        image = torch.tensor(image, dtype=torch.float32).permute(2, 0, 1)
        mask = torch.tensor(mask, dtype=torch.float32).unsqueeze(0)

        return image, mask

# DataLoader Setup
dataset = MiniSegmentationDataset("mini_dataset/images", "mini_dataset/masks")
dataloader = DataLoader(dataset, batch_size=2, shuffle=True)

# 3. Simple Segmentation Model (Mini U-Net)
class MiniUNet(nn.Module):
    def __init__(self):
        super(MiniUNet, self).__init__()
        self.enc1 = nn.Sequential(nn.Conv2d(3, 16, 3, padding=1), nn.ReLU())
        self.pool = nn.MaxPool2d(2, 2)
        self.middle = nn.Sequential(nn.Conv2d(16, 32, 3, padding=1), nn.ReLU())
        self.up = nn.ConvTranspose2d(32, 16, 2, stride=2)
        self.dec1 = nn.Sequential(nn.Conv2d(16, 1, 3, padding=1), nn.Sigmoid())

    def forward(self, x):
        x1 = self.enc1(x)
        x2 = self.pool(x1)
        x3 = self.middle(x2)
        x4 = self.up(x3)
        out = self.dec1(x4)
        return out

# 4. Training Loop
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = MiniUNet().to(device)
criterion = nn.BCELoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

print(f"Training on {device}...")
model.train()
for epoch in range(5):
    epoch_loss = 0
    for imgs, masks in dataloader:
        imgs, masks = imgs.to(device), masks.to(device)

        optimizer.zero_grad()
        outputs = model(imgs)
        loss = criterion(outputs, masks)
        loss.backward()
        optimizer.step()

        epoch_loss += loss.item()
    print(f"Epoch {epoch+1}/5 - Loss: {epoch_loss/len(dataloader):.4f}")

# 5. Visualization
model.eval()
test_img, test_mask = dataset[0]
with torch.no_grad():
    pred_mask = model(test_img.unsqueeze(0).to(device)).cpu().squeeze().numpy()

fig, ax = plt.subplots(1, 3, figsize=(12, 4))
ax[0].imshow(test_img.permute(1, 2, 0).numpy())
ax[0].set_title("Input Image")
ax[1].imshow(test_mask.squeeze().numpy(), cmap="gray")
ax[1].set_title("Ground Truth Mask")
ax[2].imshow(pred_mask > 0.5, cmap="gray")
ax[2].set_title("Predicted Mask")
plt.show()

